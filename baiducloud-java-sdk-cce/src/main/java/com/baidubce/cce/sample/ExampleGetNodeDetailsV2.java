package com.baidubce.cce.sample;

import com.baidubce.BceClientConfiguration;
import com.baidubce.BceClientException;
import com.baidubce.auth.DefaultBceCredentials;
import com.baidubce.cce.CceClient;
import com.baidubce.cce.models.GetNodeDetailsV2Request;
import com.baidubce.cce.models.GetNodeDetailsV2Response;

public class ExampleGetNodeDetailsV2 {
    public static void main(String[] args) {
        String endpoint = "Your Endpoint";
        BceClientConfiguration bceClientConfig = new BceClientConfiguration();
        bceClientConfig.setEndpoint(endpoint);

        // ==== AK/SK 鉴权 ====
        String ak = "Your Ak";
        String sk = "Your Sk";
        bceClientConfig.setCredentials(new DefaultBceCredentials(ak, sk));

        CceClient client = new CceClient(bceClientConfig);
        GetNodeDetailsV2Request getNodeDetailsV2Request = new GetNodeDetailsV2Request();
        getNodeDetailsV2Request.setClusterID("");
        getNodeDetailsV2Request.setInstanceID("");
        try {
            GetNodeDetailsV2Response response = client.getNodeDetailsV2(getNodeDetailsV2Request);
            System.out.println(response.toJsonString());
        } catch (BceClientException e) {
            System.out.println(e.getMessage());
        }
    }
}
